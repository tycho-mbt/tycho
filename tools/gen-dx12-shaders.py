#!/usr/bin/env python3
"""Compile the DX12 example HLSL into embedded MoonBit FixedArray[UInt32] DXIL constants.

Usage: python tools/gen-dx12-shaders.py [--check]

The generated file is committed so the examples never need dxc at build or run
time; --check regenerates into a buffer and fails on any drift (CI gate).
"""

from __future__ import annotations

import os
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXAMPLE = ROOT / "examples" / "74-dx12-triangle"
SOURCE = EXAMPLE / "shaders.hlsl"
OUTPUT = EXAMPLE / "shaders_dxil.mbt"

# (identifier, entry point, profile)
ENTRIES = [
    ("dx12_triangle_vs", "vs_main", "vs_6_0"),
    ("dx12_triangle_ps", "ps_main", "ps_6_0"),
]


def find_dxc() -> str:
    env = os.environ.get("TYCHO_DXC")
    if env and pathlib.Path(env).is_file():
        return env
    found = shutil.which("dxc")
    if found:
        return found
    sdk = os.environ.get("VULKAN_SDK")
    candidates = []
    if sdk:
        candidates.append(pathlib.Path(sdk) / "Bin" / "dxc.exe")
    kits = pathlib.Path("C:/Program Files (x86)/Windows Kits/10/bin")
    if kits.is_dir():
        for version in sorted(kits.iterdir(), reverse=True):
            candidates.append(version / "x64" / "dxc.exe")
    for cand in candidates:
        if cand.is_file():
            return str(cand)
    raise FileNotFoundError("dxc not found (set TYCHO_DXC, add it to PATH, or install the Vulkan SDK)")


def compile_entry(dxc: str, entry: str, profile: str) -> list[int]:
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "out.dxil"
        subprocess.run(
            [dxc, "-T", profile, "-E", entry, "-Fo", str(out), str(SOURCE)],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        data = out.read_bytes()
    padded = data + b"\x00" * ((4 - len(data) % 4) % 4)
    return [len(data)] + [w[0] for w in struct.iter_unpack("<I", padded)]


def render(compiled: list[tuple[str, list[int]]]) -> str:
    lines = [
        "// Generated by tools/gen-dx12-shaders.py - DO NOT EDIT.",
        "",
        "// Embedded DXIL bytecode (SM 6.0) compiled from shaders.hlsl, stored as",
        "// little-endian 32-bit words; the companion *_bytes constants carry the",
        "// exact byte length so trailing padding never reaches the driver.",
        "",
    ]
    for name, words in compiled:
        length = words[0]
        body = words[1:]
        lines.append(f"///|")
        lines.append(f"let {name} : FixedArray[UInt32] = [")
        for i in range(0, len(body), 8):
            chunk = ", ".join(f"(0x{word:08X} : UInt32)" for word in body[i : i + 8])
            lines.append(f"  {chunk},")
        lines.append("]")
        lines.append("")
        lines.append(f"///|")
        lines.append(f"let {name}_bytes : Int = {length}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    check_only = "--check" in sys.argv[1:]
    dxc = find_dxc()
    compiled = [(name, compile_entry(dxc, entry, profile)) for name, entry, profile in ENTRIES]
    rendered = render(compiled)
    if check_only:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != rendered:
            print(f"ERROR: {OUTPUT} is out of date; run tools/gen-dx12-shaders.py", file=sys.stderr)
            return 1
        print("dx12 shaders in sync")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    total = sum(words[0] for _, words in compiled)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({total} DXIL bytes, {len(compiled)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
