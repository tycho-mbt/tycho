#!/usr/bin/env python3
"""Compile a Slang source into BOTH artifacts (SPIR-V + DXIL) as MoonBit constants.

Usage: python tools/gen-dual-shaders.py [--check]

This is the build-time half of the "one Slang source, two backends" decision
(docs/original-design/03-dx12.md §6.1 item 1): every entry point is emitted as a
SPIR-V word array for Vulkan and a DXIL word array plus exact byte length for
DX12. Both live in one committed `.mbt`, so neither `moon build` nor CI needs
`slangc` at run time.
"""

from __future__ import annotations

import os
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent

# (package dir, slang source, generated file, [(identifier, entry, stage)])
TARGETS = [
    (
        "examples/82-dx12-indirect",
        "shader.slang",
        "shader_artifacts.mbt",
        [
            ("shader_vs", "vertexMain", "vertex"),
            ("shader_fs", "fragmentMain", "fragment"),
        ],
    ),
    (
        "examples/81-dx12-geometry",
        "shader.slang",
        "shader_artifacts.mbt",
        [
            ("shader_vs", "vertexMain", "vertex"),
            ("shader_fs", "fragmentMain", "fragment"),
        ],
    ),
    (
        "examples/80-dx12-compute",
        "shader.slang",
        "shader_artifacts.mbt",
        [("shader_cs", "computeMain", "compute")],
    ),
    (
        "examples/79-dx12-texture",
        "shader.slang",
        "shader_artifacts.mbt",
        [
            ("shader_vs", "vertexMain", "vertex"),
            ("shader_fs", "fragmentMain", "fragment"),
        ],
    ),
    (
        "examples/78-dx12-depth",
        "shader.slang",
        "shader_artifacts.mbt",
        [
            ("shader_vs", "vertexMain", "vertex"),
            ("shader_fs", "fragmentMain", "fragment"),
        ],
    ),
    (
        "examples/77-dx12-uniform",
        "shader.slang",
        "shader_artifacts.mbt",
        [
            ("shader_vs", "vertexMain", "vertex"),
            ("shader_fs", "fragmentMain", "fragment"),
        ],
    ),
]


def find_slangc() -> str:
    env = os.environ.get("TYCHO_SLANGC")
    if env and pathlib.Path(env).is_file():
        return env
    found = shutil.which("slangc")
    if found:
        return found
    candidates = []
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        candidates.append(pathlib.Path(sdk) / "Bin" / "slangc.exe")
    for cand in candidates:
        if cand.is_file():
            return str(cand)
    raise FileNotFoundError("slangc not found (set TYCHO_SLANGC, add it to PATH, or install the Vulkan SDK)")


def compile_entry(slangc: str, source: pathlib.Path, entry: str, stage: str, target: str) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / f"out.{target}"
        subprocess.run(
            [
                slangc,
                str(source),
                "-target",
                target,
                "-profile",
                "sm_6_0",
                "-entry",
                entry,
                "-stage",
                stage,
                "-o",
                str(out),
            ],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        return out.read_bytes()


def words(data: bytes) -> list[int]:
    padded = data + b"\x00" * ((4 - len(data) % 4) % 4)
    return [w[0] for w in struct.iter_unpack("<I", padded)]


def emit_array(name: str, body: list[int]) -> list[str]:
    lines = ["///|", f"let {name} : FixedArray[UInt32] = ["]
    for i in range(0, len(body), 8):
        chunk = ", ".join(f"(0x{word:08X} : UInt32)" for word in body[i : i + 8])
        lines.append(f"  {chunk},")
    lines.append("]")
    lines.append("")
    return lines


def render(source_name: str, compiled: list[tuple[str, bytes, bytes]]) -> str:
    lines = [
        "// Generated by tools/gen-dual-shaders.py - DO NOT EDIT.",
        "",
        f"// One Slang source ({source_name}) compiled for both backends by slangc:",
        "// SPIR-V words for Vulkan, DXIL words plus the exact byte length for DX12.",
        "// Having both committed is what lets the RHI pick an artifact at run time",
        "// without a shader compiler on the target machine.",
        "",
    ]
    for name, spv, dxil in compiled:
        lines.extend(emit_array(f"{name}_spv", words(spv)))
        lines.extend(emit_array(f"{name}_dxil", words(dxil)))
        lines.append("///|")
        lines.append(f"let {name}_dxil_bytes : Int = {len(dxil)}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    check_only = "--check" in sys.argv[1:]
    slangc = find_slangc()
    drift = 0
    for package, source_name, output_name, entries in TARGETS:
        package_dir = ROOT / package
        source = package_dir / source_name
        output = package_dir / output_name
        compiled = [
            (
                name,
                compile_entry(slangc, source, entry, stage, "spirv"),
                compile_entry(slangc, source, entry, stage, "dxil"),
            )
            for name, entry, stage in entries
        ]
        rendered = render(source_name, compiled)
        spv_total = sum(len(spv) for _, spv, _ in compiled)
        dxil_total = sum(len(dxil) for _, _, dxil in compiled)
        if check_only:
            current = output.read_text(encoding="utf-8") if output.is_file() else ""
            if current != rendered:
                print(f"ERROR: {output} is out of date; run tools/gen-dual-shaders.py", file=sys.stderr)
                drift = 1
            else:
                print(
                    f"{output.relative_to(ROOT)} in sync "
                    f"(SPIR-V {spv_total} B, DXIL {dxil_total} B)"
                )
        else:
            output.write_text(rendered, encoding="utf-8", newline="\n")
            print(
                f"wrote {output.relative_to(ROOT)} "
                f"(SPIR-V {spv_total} B, DXIL {dxil_total} B, {len(compiled)} entry points)"
            )
    return drift


if __name__ == "__main__":
    sys.exit(main())
