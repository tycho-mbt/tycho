#!/usr/bin/env python3
"""Compile GLSL shaders into embedded MoonBit FixedArray[UInt32] SPIR-V constants."""

from __future__ import annotations

import os
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile


def find_glslang() -> str:
    found = shutil.which("glslangValidator")
    if found:
        return found
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        cand = pathlib.Path(sdk) / "bin" / "glslangValidator"
        if cand.is_file():
            return str(cand)
    home = pathlib.Path.home()
    for p in sorted((home / "VulkanSDK").glob("*/x86_64/bin/glslangValidator")):
        if p.is_file():
            return str(p)
    raise FileNotFoundError("glslangValidator not found in PATH or VULKAN_SDK")


def compile_shader(glslang: str, src: pathlib.Path) -> list[int]:
    with tempfile.TemporaryDirectory() as tmp:
        spv_path = pathlib.Path(tmp) / "out.spv"
        subprocess.run(
            [glslang, "-V", "--target-env", "vulkan1.0", str(src), "-o", str(spv_path)],
            check=True,
        )
        data = spv_path.read_bytes()
    if len(data) % 4 != 0:
        raise ValueError(f"Invalid SPIR-V byte length for {src}: {len(data)}")
    return [w[0] for w in struct.iter_unpack("<I", data)]


def sanitize_ident(filename: str) -> str:
    return "spv_" + filename.replace(".", "_").replace("-", "_").lower()


def generate_file(src_dir: pathlib.Path, out_file: pathlib.Path) -> None:
    glslang = find_glslang()
    sources = sorted(
        p
        for p in src_dir.iterdir()
        if p.is_file() and p.suffix in (".vert", ".frag", ".comp")
    )
    lines = [
        "// Generated by tools/compile-embedded-shaders.py — DO NOT EDIT.",
        "// Embedded Vulkan 1.3 SPIR-V bytecode arrays (zero runtime glslangValidator dependency).",
        "",
    ]
    for src in sources:
        words = compile_shader(glslang, src)
        ident = sanitize_ident(src.name)
        lines.append("///|")
        lines.append(f"let {ident} : FixedArray[UInt32] = [")
        for i in range(0, len(words), 8):
            chunk = words[i : i + 8]
            formatted = ", ".join(f"(0x{w:08X} : UInt32)" for w in chunk)
            lines.append(f"  {formatted},")
        lines.append("]")
        lines.append("")
    out_file.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {out_file} ({len(sources)} shaders)")


if __name__ == "__main__":
    root = pathlib.Path(__file__).resolve().parent.parent
    src_dir = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "2d" / "shaders"
    out_file = (
        pathlib.Path(sys.argv[2])
        if len(sys.argv) > 2
        else root / "2d" / "shaders_spv.mbt"
    )
    generate_file(src_dir, out_file)
